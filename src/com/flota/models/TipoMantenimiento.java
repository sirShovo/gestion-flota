package com.flota.models;

/**
 * Enumeración para clasificar los tipos de mantenimiento de los vehículos.
 */
public enum TipoMantenimiento {
    /**
     * Mantenimiento de rutina para evitar fallas (cambio de aceite, filtros, revisión general).
     */
    PREVENTIVO,

    /**
     * Reparación de fallas o daños ya existentes en el vehículo.
     */
    CORRECTIVO
}
